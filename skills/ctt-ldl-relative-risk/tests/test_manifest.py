"""Printed examples first: Discussion, CTT Collaboration, Lancet 2010.

The paper explicitly multiplies 0.78 by 0.78 for a 2 mmol/L reduction,
reporting RR about 0.6. The expected value below is that printed number,
not a number generated by our implementation. One decimal => tolerance 0.05.
"""
import json
from pathlib import Path
import subprocess
import sys

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from personal_report import calculate
import presets


def test_printed_two_mmol_example():
    assert calculate(2)['major_vascular_rr'] == pytest.approx(0.6, abs=0.05)


def test_printed_unit_reduction():
    # Summary Findings and Results / Figure 1, all 26 trials.
    result = calculate(1.0)
    assert result['major_vascular_rr'] == pytest.approx(0.78)
    assert result['rr_ci95_lower'] == pytest.approx(0.76)
    assert result['rr_ci95_upper'] == pytest.approx(0.80)
    assert result['relative_reduction_pct'] == pytest.approx(22)


def test_printed_three_mmol_example():
    # Discussion: 3 mmol/L gives about 50% reduction, rounded to tens of percent.
    # This also rejects linear subtraction of the per-mmol percentage.
    assert calculate(3)['relative_reduction_pct'] == pytest.approx(50, abs=5)


def test_fractional_reductions_compose_to_printed_rr():
    # Two half-unit changes must compose to the printed one-unit RR of 0.78.
    half = calculate(0.5)['major_vascular_rr']
    assert half * half == pytest.approx(0.78)


def run(tmp_path, text, target=None):
    path = tmp_path / 'input.csv'
    path.write_text(text, encoding='utf-8')
    out = tmp_path / 'out'
    cmd = [sys.executable, str(ROOT / 'scripts/personal_report.py'),
           '--measurements', str(path), '--out', str(out)]
    if target is not None:
        target_path = tmp_path / 'target.csv'
        target_path.write_text(target, encoding='utf-8')
        cmd += ['--targets', str(target_path)]
    result = subprocess.run(cmd, capture_output=True, text=True)
    return result, out


def test_manifest_matches_presets():
    m = json.loads((ROOT / 'skill.json').read_text())
    spec, = m['inputs']
    assert spec['key'] == presets.INPUT_KEY
    assert spec['unit'] == presets.INPUT_UNIT
    assert spec['range'] == list(presets.REDUCTION_RANGE)
    assert spec['accept']['mg/dL'] == presets.MG_DL_TO_MMOL_L == 0.02586
    assert m['validation']['status'] == 'reproduced'


def test_cli_printed_example_and_targets(tmp_path):
    result, out = run(tmp_path, 'marker,value,unit\nLDL-C reduction,1,mmol/L\n',
                      'marker,value,unit\nLDL-C reduction,2,mmol/L\n')
    assert result.returncode == 0, result.stderr
    data = json.loads((out / 'result.json').read_text())['outputs']
    assert data['major_vascular_rr']['value'] == pytest.approx(0.78)
    levers = json.loads((out / 'levers.json').read_text())
    assert levers['targets']['major_vascular_rr'] == pytest.approx(0.6, abs=0.05)
    assert len(levers['levers']) == 1
    assert levers['levers'][0]['major_vascular_rr'] == levers['targets']['major_vascular_rr']
    assert levers['sensitivity'][0]['rr_per_unit'] < 0
    report = (out / 'report.md').read_text()
    assert report.index('## 论文卡片') < report.index('## 你的结果')
    assert '边界:' in report and '不能据此开始或停止用药' in report
    assert '个人预测区间' in report and '目标' in report


def test_published_unit_conversion(tmp_path):
    # Webtable 1 footnote: mmol/L -> mg/dL divide by 0.02586.
    result, out = run(tmp_path, f'marker,value,unit\nLDL-C reduction,{1 / 0.02586},mg/dL\n')
    assert result.returncode == 0, result.stderr
    assert json.loads((out / 'result.json').read_text())['outputs']['major_vascular_rr']['value'] == pytest.approx(0.78)


@pytest.mark.parametrize('row', ['LDL-C reduction,1,g/L', 'LDL-C reduction,4,mmol/L',
    'LDL-C reduction,-1,mmol/L', 'LDL-C reduction,nan,mmol/L', 'LDL-C reduction,1,',
    'LDL-C,2,mmol/L', 'LDL-C reduction,,mmol/L', ''])
def test_bad_or_missing_input_exits_three(tmp_path, row):
    result, out = run(tmp_path, 'marker,value,unit\n' + row + '\n')
    assert result.returncode == 3, result.stderr
    assert json.loads((out / 'problems.json').read_text())['problems']
    data = json.loads((out / 'result.json').read_text())['outputs']
    assert all(x['value'] is None for x in data.values())
    assert not (out / 'levers.json').exists()
    report = (out / 'report.md').read_text()
    assert '这次没有计算' in report and '## 论文卡片' in report


def test_bad_target_clears_stale_outputs(tmp_path):
    valid = 'marker,value,unit\nLDL-C reduction,1,mmol/L\n'
    result, out = run(tmp_path, valid)
    assert result.returncode == 0
    result, out = run(tmp_path, valid, 'marker,value,unit\nLDL-C,2,mmol/L\n')
    assert result.returncode == 3
    assert not (out / 'levers.json').exists()
    assert all(x['value'] is None for x in json.loads((out / 'result.json').read_text())['outputs'].values())


def test_missing_file_exits_three(tmp_path):
    result = subprocess.run([sys.executable, str(ROOT / 'scripts/personal_report.py'),
        '--measurements', str(tmp_path / 'missing.csv'), '--out', str(tmp_path / 'out')])
    assert result.returncode == 3
