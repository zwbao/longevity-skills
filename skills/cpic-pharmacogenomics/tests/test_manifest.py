def test_missing_file_exits_3(tmp_path):
    assert _exit(["--genotype", str(tmp_path / "nope.txt"), "--out", str(tmp_path / "out")]) == skillkit.EXIT_INPUT_PROBLEM


def test_good_file_exits_0(tmp_path):
    path = _file(tmp_path, HEADER_23ANDME + "rs4244285\t10\t96541616\tAG\n")
