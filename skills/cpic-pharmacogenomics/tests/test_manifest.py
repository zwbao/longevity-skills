def test_23andme_rows_and_no_calls(tmp_path):
    path = _file(tmp_path, HEADER_23ANDME + "rs4244285\t10\t96541616\tAG\nrs4986893\t10\t96540410\t--\nrs41303343\t7\t99250393\tDI\n")
    parsed = read_genotype_file(path)
    assert parsed.format == "23andme" and parsed.build_note == "GRCh37"
    assert parsed.genotype("rs4244285") == "AG"
    assert "rs4986893" in parsed.no_calls
    assert parsed.genotype("rs41303343") == "DI"


def test_wegene_header_and_two_letter_calls(tmp_path):
    text = "# WeGene raw data\n# rsid\tchromosome\tposition\tgenotype\nrs4244285\t10\t96541616\tAA\nrs2032598\tY\t2821400\tTT\n"
    parsed = read_genotype_file(_file(tmp_path, text))
    assert parsed.format == "wegene"
    assert parsed.genotype("rs4244285") == "AA"


def test_ancestrydna_five_columns(tmp_path):
    text = "#AncestryDNA raw data download\nrsid\tchromosome\tposition\tallele1\tallele2\nrs4244285\t10\t96541616\tG\tA\n"
    parsed = read_genotype_file(_file(tmp_path, text))
    assert parsed.format == "ancestrydna" and parsed.genotype("rs4244285") == "GA"


def test_comma_gz_and_zip(tmp_path):
    csv_text = "rsid,chromosome,position,genotype\nrs4244285,10,96541616,AG\n"
    assert read_genotype_file(_file(tmp_path, csv_text, "a.csv")).genotype("rs4244285") == "AG"
    gz = tmp_path / "a.txt.gz"
    gz.write_bytes(gzip.compress((HEADER_23ANDME + "rs4244285\t10\t96541616\tAG\n").encode()))
    assert read_genotype_file(gz).genotype("rs4244285") == "AG"
    zipped = tmp_path / "a.zip"
    with zipfile.ZipFile(zipped, "w") as archive:
        archive.writestr("genome.txt", HEADER_23ANDME + "rs4244285\t10\t96541616\tAG\n")
    assert read_genotype_file(zipped).genotype("rs4244285") == "AG"


def test_empty_file_is_an_error(tmp_path):
    try:
        read_genotype_file(_file(tmp_path, "# only comments\n"))
    except GenotypeFileError as error:
        assert "没有找到基因型行" in error.message_zh
    else:
        raise AssertionError("expected GenotypeFileError")


def test_shared_parser_copies_are_identical():
    other = ROOT.parent / "nutrigenetic-variant-panel" / "scripts" / "genotype_file.py"
    if other.exists():
        assert other.read_bytes() == (ROOT / "scripts" / "genotype_file.py").read_bytes()

