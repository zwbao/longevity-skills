def test_appendix_woman():
    # Appendix Case 1: age 61, TC 180, HDL 47, untreated SBP 124,
    # smoker, not diabetic; printed sum 26.9653, risk 0.1048 ≈ 10.5%.
    result = report.compute({'sbp_mmhg': 124, 'tc_mg_dl': 180, 'hdl_mg_dl': 47},
                            61, 'female', False, True, False, 'lipids')
    assert result['linear_predictor'] == pytest.approx(26.9653, abs=0.0001)
    assert result['risk_10y_pct'] == pytest.approx(10.5, abs=0.05)
    assert result['normal_risk_10y_pct'] == pytest.approx(6.7, abs=0.05)


