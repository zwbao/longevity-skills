@pytest.mark.parametrize('sex,treated,expected', [
    ('male', False, 0.0177611311514575),
    ('male', True, 0.02500868554244895),
    ('female', False, 0.010801167676829593),
    ('female', True, 0.015094153510678776),
])
def test_official_bmi_workbook(sex, treated, expected):
    # Official gencardio_bmi.xls, Sheet2 row 28 D:G (cached Risk Score).
    # Input Sheet_2: age 30, SBP 125, BMI 22.5, no smoking or diabetes.
    result = report.compute({'sbp_mmhg': 125, 'bmi_kg_m2': 22.5},
                            30, sex, treated, False, False, 'bmi')
