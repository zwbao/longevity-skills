def csv(path, text):
    path.write_text('marker,value,unit\n' + text)
    return path


def run(tmp_path, rows=None, extra=(), omit=()):
    rows = rows if rows is not None else '收缩压,124,mmHg\n总胆固醇,180,mg/dL\nHDL-C,47,mg/dL\n'
    path = csv(tmp_path / 'input.csv', rows)
    options = {'--age': '61', '--sex': 'female', '--treated': 'no',
               '--smoker': 'yes', '--diabetes': 'no', '--prior-cvd': 'no'}
    args = [sys.executable, str(ROOT / 'scripts/personal_report.py'), '--measurements', str(path),
            '--out', str(tmp_path / 'out')]
    for key, value in options.items():
        if key not in omit:
            args += [key, value]
    return subprocess.run(args + list(extra), text=True, capture_output=True)


def test_manifest_units():
    specs = {s['key']: s for s in MANIFEST['inputs']}
    for key, unit in presets.MEASUREMENT_UNITS.items():
        assert specs[key]['unit'] == unit
    assert set(presets.MODEL_KEYS['lipids']) == {'sbp_mmhg', 'tc_mg_dl', 'hdl_mg_dl'}
    assert set(presets.MODEL_KEYS['bmi']) == {'sbp_mmhg', 'bmi_kg_m2'}


def test_cli_paper_example_and_units(tmp_path):
    result = run(tmp_path)
    assert result.returncode == 0, result.stderr
    output = json.loads((tmp_path / 'out/result.json').read_text())['outputs']
    assert output['risk_10y_pct']['value'] == pytest.approx(10.5, abs=0.05)
    text = (tmp_path / 'out/report.md').read_text()
    assert text.index('论文卡片') < text.index('## 个人结果')
    assert '10.1161/circulationaha.107.699579' in text
    assert presets.BOUNDARY in text
    assert (tmp_path / 'out/levers.json').exists()
    converted = run(tmp_path, f'SBP,{124/7.500617},kPa\nTC,{180/38.665},mmol/L\nHDL-C,{47/38.665},mmol/L\n')
    assert converted.returncode == 0, converted.stderr
    converted_output = json.loads((tmp_path / 'out/result.json').read_text())['outputs']
    assert converted_output == output


@pytest.mark.parametrize('rows,extra,omit', [
    ('SBP,124,mg/dL\nTC,180,mg/dL\nHDL-C,47,mg/dL\n', (), ()),
    ('SBP,900,mmHg\nTC,180,mg/dL\nHDL-C,47,mg/dL\n', (), ()),
    ('SBP,124,mmHg\nTC,180,mg/dL\n', (), ()),
    ('SBP,nan,mmHg\nTC,180,mg/dL\nHDL-C,47,mg/dL\n', (), ()),
    (None, (), ('--smoker',)),
    (None, ('--age', 'abc'), ()),
    (None, ('--age', '75'), ()),
    (None, ('--sex', 'unknown'), ()),
    (None, ('--diabetes', 'unknown'), ()),
    (None, ('--prior-cvd', 'yes'), ()),
    (None, (), ('--prior-cvd',)),
    (None, ('--model', 'other'), ()),
])
def test_invalid_inputs_exit_three(tmp_path, rows, extra, omit):
    assert run(tmp_path).returncode == 0  # Ensure a failed rerun cannot leave stale results.
    result = run(tmp_path, rows, extra, omit)
    assert result.returncode == 3, result.stderr
    out = tmp_path / 'out'
    assert json.loads((out / 'problems.json').read_text())['problems']
    assert not (out / 'result.json').exists()
    assert not (out / 'levers.json').exists()
    text = (out / 'report.md').read_text()
    assert '这次没有计算' in text and '10.5%' not in text
    assert '论文卡片' in text and presets.BOUNDARY in text


def test_targets_and_bmi_mode(tmp_path):
    target = csv(tmp_path / 'target.csv', 'SBP,125,mmHg\nTC,180,mg/dL\nHDL-C,45,mg/dL\n')
    # Same-sex reference factors reproduce the printed man's normal risk 9.1%.
    result = run(tmp_path, extra=('--age','53','--sex','male','--smoker','no','--targets',str(target)))
    assert result.returncode == 0, result.stderr
    levers = json.loads((tmp_path / 'out/levers.json').read_text())
    assert levers['targets']['risk_pct'] == pytest.approx(9.1, abs=0.05)
    assert len(levers['levers']) == 3
    result = run(tmp_path, 'SBP,125,mmHg\nBMI,22.5,kg/m^2\n',
                 ('--model','bmi','--age','30','--smoker','no'))
    assert result.returncode == 0, result.stderr
    output = json.loads((tmp_path / 'out/result.json').read_text())['outputs']
    assert output['risk_10y_pct']['value']/100 == pytest.approx(0.010801167676829593)


