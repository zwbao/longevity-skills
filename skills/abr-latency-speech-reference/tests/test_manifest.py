@pytest.mark.parametrize("kwargs,kind", [
    ({"unit": "dB"}, "unit"),
    ({"latency": "1830"}, "range"),
    ({"latency": ""}, "missing"),
    ({"latency": "NaN"}, "parse"),
    ({"latency": ">1.83"}, "parse"),
    ({"latency": "1.5"}, "unsupported_grid"),
    ({"latency": "1.2666667"}, "unsupported_grid"),
    ({"age": "60"}, "unsupported_grid"),
    ({"age": None}, "missing"),
    ({"age": "NaN"}, "parse"),
    ({"age": "85"}, "range"),
    ({"sex": "invalid"}, "category"),
])
def test_invalid_inputs_exit3_without_scores(tmp_path, kwargs, kind):
    proc, out = run_report(tmp_path, **kwargs)
    assert proc.returncode == 3, proc.stderr
    problems = json.loads((out / "problems.json").read_text())["problems"]
    assert kind in {p["kind"] for p in problems}
    assert all(v is None for v in outputs(out).values())
    report = (out / "report.md").read_text()
    assert "55.576" not in report and "## 论文卡片" in report and "边界:" in report


def test_report_scope_and_rerun_cleanup(tmp_path):
    proc, out = run_report(tmp_path, sex="女")
    assert proc.returncode == 0
    report = (out / "report.md").read_text()
    assert report.index("## 论文卡片") < report.index("## 原表参考值")
    for phrase in ["预印本，未经同行评审", "男性参考设定", "不是个人预测区间", "边界:", "不调整"]:
        assert phrase in report
    # A failed rerun must overwrite an earlier successful result.
    proc, out = run_report(tmp_path, latency="1.5")
    assert proc.returncode == 3
    assert all(v is None for v in outputs(out).values())
    proc, out = run_report(tmp_path)
    assert proc.returncode == 0 and not (out / "problems.json").exists()
