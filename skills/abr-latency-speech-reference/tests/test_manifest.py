"""Expected values are printed cells of v3 Table S12, supplement p. 19.

These tests validate a discrete table reader, not independent reconstruction of
the S9 regression. No expected score is generated by the implementation.
"""

import json
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))


def run_report(tmp_path, latency="1.83", unit="ms", age="75", marker="ABR波I潜伏期", sex=None):
    measurements = tmp_path / "measurements.csv"
    measurements.write_text(f"marker,value,unit\n{marker},{latency},{unit}\n", encoding="utf-8")
    out = tmp_path / "out"
    args = [sys.executable, str(ROOT / "scripts/personal_report.py"),
            "--measurements", str(measurements), "--out", str(out)]
    if age is not None:
        args += ["--age", age]
    if sex is not None:
        args += ["--sex", sex]
    proc = subprocess.run(args, capture_output=True, text=True)
    return proc, out


def outputs(out):
    return {k: v["value"] for k, v in json.loads((out / "result.json").read_text())["outputs"].items()}


def test_table_s12_age75_maximum(tmp_path):
    # Age Group W1.Latency Level W1.Lat (ms) Predicted SE 95% CI [L] [U]
    # WS: 75 Maximum 1.83 55.5767880023087 6.30956600884295 43.1565808286259 67.9969951759915
    # PS: 75 Maximum 1.83 80.3626538616887 4.14018202793002 72.212819395803 88.5124883275744
    proc, out = run_report(tmp_path)
    assert proc.returncode == 0, proc.stderr
    result = outputs(out)
    assert result == pytest.approx({
        "ws_reference_pct": 55.5767880023087, "ws_mean_se_pp": 6.30956600884295,
        "ws_mean_ci_lower_pct": 43.1565808286259, "ws_mean_ci_upper_pct": 67.9969951759915,
        "ps_reference_pct": 80.3626538616887, "ps_mean_se_pp": 4.14018202793002,
        "ps_mean_ci_lower_pct": 72.212819395803, "ps_mean_ci_upper_pct": 88.5124883275744,
    }, rel=0, abs=1e-12)


