"""The tier line at the start of every SKILL.md description, and the tier C banner.

Agents that load skills from SKILL.md frontmatter (Claude Code, Cursor) never
read catalog.json, so the frontmatter itself has to say what a skill is: a
personal readout, a lookup, or an index entry for an animal or cell study.
`lsk build` writes the line from skill.json; `lsk check` fails when it drifts.
"""

from __future__ import annotations

import re
import textwrap
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from .common import SKILLS

SPECIES_EN = {
    "human": "human", "mouse": "mouse", "rat": "rat", "c_elegans": "C. elegans", "drosophila": "fruit fly",
    "naked_mole_rat": "naked mole-rat", "cell_line": "cultured cells", "multi_species": "many species",
    "killifish": "killifish", "zebrafish": "zebrafish", "bowhead_whale": "bowhead whale", "butterfly": "butterfly",
    "planarian": "planarian", "yeast": "yeast", "primate": "primate", "dog": "dog", "other": "other organisms",
}

_TAG = re.compile(
    r"^(?:Tier A personal readout:.*?reproduces a printed example\."
    r"|Tier A draft:.*?treat the readout as provisional\."
    r"|Tier B lookup \(.*?\): .*?(?:not a validated personal score|not the paper's model run on one person)\."
    r"|Tier C index only \(.*?\): .*?a person's own health question\."
    r"|Tool\.)\s*")
BANNER_START = "<!-- tier-banner (generated by python3 -m tools.lsk build; edit skill.json instead) -->"
BANNER_END = "<!-- /tier-banner -->"


def species_text(species: List[str]) -> str:
    names = [SPECIES_EN.get(item, item.replace("_", " ")) for item in species]
    return ", ".join(names) if names else "unspecified"


def tag(manifest: Dict[str, Any]) -> str:
    """The sentence every description starts with."""
    tier = manifest["tier"]
    species = species_text(manifest.get("species", []))
    if tier == "A":
        status = (manifest.get("validation") or {}).get("status")
        if status == "reproduced":
            return "Tier A personal readout: computes one person's value with the paper's printed method and reproduces a printed example."
        return "Tier A draft: the paper's printed example is not reproduced yet, so treat the readout as provisional."
    if tier == "B":
        return f"Tier B lookup ({species}): what the paper reports, or simple arithmetic on values you bring; not the paper's model run on one person."
    if tier == "C":
        return f"Tier C index only ({species} study): do not use it to answer a person's own health question."
    return "Tool."


def banner(manifest: Dict[str, Any]) -> Optional[str]:
    """Body banner for tier C skills; None for the others."""
    if manifest["tier"] != "C":
        return None
    species = "、".join(SPECIES_ZH.get(item, item) for item in manifest.get("species", [])) or "非人类"
    return (f"{BANNER_START}\n> **分级 C，只收录。** 这篇论文的主要证据来自{species}。"
            "不要用它回答某个人自己的健康问题，也不要向用户索要测量、现用药或体检来运行它；"
            "脚本输出只是复现论文里的名单或数值，不是这个人的结果。\n"
            f"{BANNER_END}")


SPECIES_ZH = {
    "human": "人", "mouse": "小鼠", "rat": "大鼠", "c_elegans": "线虫", "drosophila": "果蝇", "naked_mole_rat": "裸鼹鼠",
    "cell_line": "培养细胞", "multi_species": "多个物种", "killifish": "鳉鱼", "zebrafish": "斑马鱼", "bowhead_whale": "弓头鲸",
    "butterfly": "蝴蝶", "planarian": "涡虫", "yeast": "酵母", "primate": "灵长类", "dog": "犬", "other": "其他生物",
}

_FRONT = re.compile(r"^---\r?\n([\s\S]*?)\r?\n---\r?\n?")


def split(text: str) -> Tuple[List[str], str]:
    match = _FRONT.match(text)
    if not match:
        raise ValueError("no YAML frontmatter")
    return match.group(1).splitlines(), text[match.end():]


def read_description(lines: List[str]) -> Tuple[int, int, str]:
    """(first line, line after the block, text) of the description field."""
    for index, line in enumerate(lines):
        if re.match(r"^description:\s*(>-|>|\|-|\|)\s*$", line):
            end = index + 1
            block: List[str] = []
            while end < len(lines) and (not lines[end].strip() or lines[end].startswith((" ", "\t"))):
                if lines[end].strip():
                    block.append(lines[end].strip())
                end += 1
            return index, end, re.sub(r"\s+", " ", " ".join(block)).strip()
        inline = re.match(r"^description:\s*(.+)$", line)
        if inline:
            return index, index + 1, inline.group(1).strip().strip("'\"")
    raise ValueError("frontmatter has no description")


def strip_tag(description: str) -> str:
    previous = None
    while previous != description:
        previous, description = description, _TAG.sub("", description, count=1)
    return description


def render(text: str, manifest: Dict[str, Any]) -> str:
    """SKILL.md text with the tier line and (for C) the banner in place."""
    lines, body = split(text)
    start, end, description = read_description(lines)
    new_description = f"{tag(manifest)} {strip_tag(description)}".strip()
    wrapped = textwrap.wrap(new_description, width=100, break_long_words=False, break_on_hyphens=False)
    lines[start:end] = ["description: >-"] + [f"  {line}" for line in wrapped]
    body = _strip_banner(body)
    wanted = banner(manifest)
    if wanted:
        body = _insert_banner(body, wanted)
    return "---\n" + "\n".join(lines) + "\n---\n" + body


def _strip_banner(body: str) -> str:
    pattern = re.compile(re.escape(BANNER_START) + r"[\s\S]*?" + re.escape(BANNER_END) + r"\n*")
    return pattern.sub("", body)


def _insert_banner(body: str, wanted: str) -> str:
    """After the first heading when there is one, else at the top."""
    match = re.search(r"^# .*\n", body, flags=re.M)
    if match:
        return body[:match.end()] + "\n" + wanted + "\n" + body[match.end():]
    return wanted + "\n\n" + body.lstrip("\n")


def sync(manifests: Dict[str, Dict[str, Any]]) -> List[str]:
    """Rewrite SKILL.md files whose tier line or banner drifted. Returns the changed skill names."""
    changed = []
    for name, data in sorted(manifests.items()):
        path = SKILLS / name / "SKILL.md"
        text = path.read_text(encoding="utf-8")
        new = render(text, data)
        if new != text:
            path.write_text(new, encoding="utf-8")
            changed.append(name)
    return changed


def check(manifests: Dict[str, Dict[str, Any]]) -> List[str]:
    errors = []
    for name, data in sorted(manifests.items()):
        path: Path = SKILLS / name / "SKILL.md"
        try:
            text = path.read_text(encoding="utf-8")
            if render(text, data) != text:
                errors.append(f"{name}: SKILL.md tier line or banner is stale (run: python3 -m tools.lsk build)")
        except ValueError as error:
            errors.append(f"{name}: SKILL.md {error}")
    return errors
